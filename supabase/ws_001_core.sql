begin;

create table if not exists public.ws_organizations (
  id uuid primary key default gen_random_uuid(),
  garage_id bigint generated by default as identity (start with 1000) unique,
  name text not null check (length(btrim(name)) between 2 and 160),
  legal_name text,
  owner_user_id uuid not null references auth.users(id) on delete restrict,
  gstin text,
  gstin_verified boolean not null default false,
  pan text,
  udyam_no text,
  address text,
  city text,
  state_code text,
  pincode text,
  lat double precision,
  lng double precision,
  phone text,
  email text,
  logo_key text,
  invoice_prefix text not null default 'TD' check (invoice_prefix ~ '^[A-Z0-9]{2,4}$'),
  upi_id text,
  status text not null default 'draft' check (status in ('draft','pending_approval','active','suspended')),
  plan text not null default 'trial' check (plan in ('trial','starter','pro','multi')),
  trial_ends_at timestamptz,
  settings jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.ws_staff (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.ws_organizations(id) on delete restrict,
  user_id uuid references auth.users(id) on delete restrict,
  name text not null check (length(btrim(name)) between 1 and 120),
  role text not null check (role in ('owner','advisor','mechanic','cashier')),
  is_active boolean not null default true,
  invited_email text,
  -- Intentionally no weak/plaintext MPIN default. M1 must provision a salted hash.
  mpin_hash text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists ws_staff_org_user_unique
  on public.ws_staff(org_id,user_id) where user_id is not null;
create index if not exists ws_staff_user_active_idx
  on public.ws_staff(user_id,org_id) where is_active and user_id is not null;

create table if not exists public.ws_counters (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.ws_organizations(id) on delete restrict,
  kind text not null check (length(btrim(kind)) between 1 and 40),
  financial_year text not null check (financial_year ~ '^[0-9]{2}-[0-9]{2}$'),
  last_value bigint not null default 0 check (last_value >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(org_id,kind,financial_year)
);

create table if not exists public.ws_audit_log (
  id bigint generated always as identity primary key,
  org_id uuid not null references public.ws_organizations(id) on delete restrict,
  actor_user_id uuid references auth.users(id) on delete set null,
  action text not null check (length(btrim(action)) between 1 and 80),
  entity text not null check (length(btrim(entity)) between 1 and 80),
  entity_id text,
  before_data jsonb,
  after_data jsonb,
  created_at timestamptz not null default now()
);
create index if not exists ws_audit_org_created_idx
  on public.ws_audit_log(org_id,created_at desc);

create table if not exists public.ws_platform_admins (
  user_id uuid primary key references auth.users(id) on delete restrict,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create or replace function public.ws_assert_active_owner()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  target_org uuid;
begin
  if tg_table_name = 'ws_organizations' then
    target_org := coalesce(new.id, old.id);
  elsif tg_op = 'DELETE' then
    target_org := old.org_id;
  else
    target_org := new.org_id;
  end if;

  if exists (select 1 from public.ws_organizations o where o.id = target_org)
     and not exists (
       select 1
       from public.ws_organizations o
       join public.ws_staff s
         on s.org_id = o.id
        and s.user_id = o.owner_user_id
       where o.id = target_org
         and s.role = 'owner'
         and s.is_active
     ) then
    raise exception 'Each workshop organization must have at least one active owner with a login.'
      using errcode = '23514', constraint = 'ws_organization_requires_active_owner';
  end if;

  if tg_op = 'UPDATE' and tg_table_name = 'ws_staff' and old.org_id is distinct from new.org_id then
    if exists (select 1 from public.ws_organizations o where o.id = old.org_id)
       and not exists (select 1 from public.ws_organizations o join public.ws_staff s on s.org_id=o.id and s.user_id=o.owner_user_id where o.id=old.org_id and s.role='owner' and s.is_active) then
      raise exception 'Each workshop organization must have at least one active owner with a login.'
        using errcode = '23514', constraint = 'ws_organization_requires_active_owner';
    end if;
  end if;
  return null;
end;
$$;
revoke all on function public.ws_assert_active_owner() from public, anon, authenticated;

drop trigger if exists ws_organizations_active_owner on public.ws_organizations;
create constraint trigger ws_organizations_active_owner
after insert or update on public.ws_organizations
deferrable initially deferred
for each row execute function public.ws_assert_active_owner();

drop trigger if exists ws_staff_active_owner on public.ws_staff;
create constraint trigger ws_staff_active_owner
after insert or update or delete on public.ws_staff
deferrable initially deferred
for each row execute function public.ws_assert_active_owner();

create or replace function public.ws_set_updated_at()
returns trigger language plpgsql
set search_path = public, pg_temp
as $$
begin
  new.updated_at := clock_timestamp();
  return new;
end;
$$;

drop trigger if exists ws_organizations_updated_at on public.ws_organizations;
create trigger ws_organizations_updated_at before update on public.ws_organizations
for each row execute function public.ws_set_updated_at();
drop trigger if exists ws_staff_updated_at on public.ws_staff;
create trigger ws_staff_updated_at before update on public.ws_staff
for each row execute function public.ws_set_updated_at();
drop trigger if exists ws_counters_updated_at on public.ws_counters;
create trigger ws_counters_updated_at before update on public.ws_counters
for each row execute function public.ws_set_updated_at();

create or replace function public.ws_is_platform_admin()
returns boolean
language sql stable security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.ws_platform_admins a
    where a.user_id = (select auth.uid()) and a.is_active
  );
$$;

create or replace function public.ws_has_role(p_org_id uuid, p_roles text[])
returns boolean
language sql stable security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.ws_staff s
    where s.org_id = p_org_id
      and s.user_id = (select auth.uid())
      and s.is_active
      and s.role = any(coalesce(p_roles, array[]::text[]))
  );
$$;

revoke all on function public.ws_is_platform_admin() from public, anon;
revoke all on function public.ws_has_role(uuid,text[]) from public, anon;
grant execute on function public.ws_is_platform_admin() to authenticated, service_role;
grant execute on function public.ws_has_role(uuid,text[]) to authenticated, service_role;

alter table public.ws_organizations enable row level security;
alter table public.ws_staff enable row level security;
alter table public.ws_counters enable row level security;
alter table public.ws_audit_log enable row level security;
alter table public.ws_platform_admins enable row level security;

drop policy if exists ws_organizations_member_select on public.ws_organizations;
create policy ws_organizations_member_select on public.ws_organizations
for select to authenticated
using (public.ws_has_role(id, array['owner','advisor','mechanic','cashier']) or public.ws_is_platform_admin());

drop policy if exists ws_staff_member_select on public.ws_staff;
create policy ws_staff_member_select on public.ws_staff
for select to authenticated
using (public.ws_has_role(org_id, array['owner','advisor','mechanic','cashier']) or public.ws_is_platform_admin());

drop policy if exists ws_staff_owner_insert on public.ws_staff;
create policy ws_staff_owner_insert on public.ws_staff
for insert to authenticated
with check (public.ws_has_role(org_id, array['owner']) or public.ws_is_platform_admin());

drop policy if exists ws_staff_owner_update on public.ws_staff;
create policy ws_staff_owner_update on public.ws_staff
for update to authenticated
using (public.ws_has_role(org_id, array['owner']) or public.ws_is_platform_admin())
with check (public.ws_has_role(org_id, array['owner']) or public.ws_is_platform_admin());

drop policy if exists ws_staff_owner_delete on public.ws_staff;
create policy ws_staff_owner_delete on public.ws_staff
for delete to authenticated
using (public.ws_has_role(org_id, array['owner']) or public.ws_is_platform_admin());

drop policy if exists ws_audit_owner_select on public.ws_audit_log;
create policy ws_audit_owner_select on public.ws_audit_log
for select to authenticated
using (public.ws_has_role(org_id, array['owner']) or public.ws_is_platform_admin());

drop policy if exists ws_platform_admin_self_select on public.ws_platform_admins;
create policy ws_platform_admin_self_select on public.ws_platform_admins
for select to authenticated
using (user_id = (select auth.uid()));

-- Counters and audit writes are Worker/RPC-only in M0. RLS is enabled and
-- intentionally has no authenticated write policies.
revoke all on public.ws_counters from anon, authenticated;
revoke all on public.ws_audit_log from anon, authenticated;
revoke all on public.ws_platform_admins from anon, authenticated;
grant select on public.ws_organizations, public.ws_staff to authenticated;
grant insert, update, delete on public.ws_staff to authenticated;
grant select on public.ws_audit_log, public.ws_platform_admins to authenticated;
grant all on public.ws_organizations, public.ws_staff, public.ws_counters, public.ws_audit_log, public.ws_platform_admins to service_role;
grant usage, select on sequence public.ws_organizations_garage_id_seq, public.ws_audit_log_id_seq to service_role;

commit;

